import main5functions
import time
import matplotlib.pyplot as plt

### TESTING ###

#array testing sizes
sizes = [1, 5, 10, 15, 20, 25, 30, 35, 40, 45, 50, 60, 70, 80, 90, 100, 110, 120, 130, 140, 150]

#number of trials done
sample_size = 10000

#Insertion sort testing
insertion_sort_times = []

for i in range(len(sizes)):
    c_time = 0
    for _ in range(sample_size):
        array = main5functions.generate_array(sizes[i])

        start_time = time.perf_counter()
        main5functions.main5_insertion_sort(array)
        end_time = time.perf_counter()

        c_time += end_time - start_time

    insertion_sort_times.append(c_time / sample_size)




#Merge sort testing

merge_sort_times = []
for i in range(len(sizes)):
    c_time = 0
    for _ in range(sample_size):
        array = main5functions.generate_array(sizes[i])

        start_time = time.perf_counter()
        main5functions.main5_merge_sort(array)
        end_time = time.perf_counter()

        c_time += end_time - start_time










































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































    merge_sort_times.append(c_time / sample_size)

#print(insertion_sort_times)
